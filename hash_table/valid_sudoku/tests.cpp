#include "valid_sudoku.hpp"

#include <gtest/gtest.h>

TEST(ValidSudoku, SimpleTest1) {
    const std::vector<std::vector<char>> desk = {
            {'3', '.', '.', '2', '.', '1', '.', '.', '.'},
            {'7', '4', '.', '.', '.', '.', '.', '1', '9'},
            {'.', '2', '.', '.', '6', '.', '5', '.', '.'},
            {'.', '3', '.', '7', '4', '.', '.', '.', '1'},
            {'.', '.', '8', '.', '.', '.', '9', '.', '.'},
            {'6', '.', '.', '.', '9', '2', '.', '5', '.'},
            {'.', '.', '2', '.', '.', '.', '.', '4', '.'},
            {'1', '5', '.', '.', '.', '.', '.', '9', '.'},
            {'.', '.', '.', '9', '.', '.', '.', '.', '2'}
    };

    EXPECT_TRUE(isValidSudoku(desk));
    EXPECT_TRUE(isValidSudoku2(desk));
}

